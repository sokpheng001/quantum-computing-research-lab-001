"""Master results table of the core work: every QVM number (real T gates, willow_pink noise)
of Google's double checks and ours in one place, with 95 % confidence intervals for the
error ratios. Reads the result files of tests 1-3 (and the stim calibration model of the
continuing-data validation); writes MASTER_RESULTS.md next to this script.

    .venv/bin/python "qvm-google (main)/master_results.py"

Ratio CI: errors are Poisson counts, so for rate ratio R = (k1 / n1) / (k2 / n2) the 95 %
interval is R * exp(+-1.96 * sqrt(1 / k1 + 1 / k2)) (log-normal approximation).
"""
import datetime as dt
import json
import math
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent
T1 = HERE / "test1_fd3_circuits_vs_google_fig2" / "results"
T2 = HERE / "test2_cs02_continuing_data_vs_google" / "results"
T3 = HERE / "test3_full_qec_realT_lowT_sim_ours_vs_google_g6" / "results" / "qvm"

# key, label, e4 file, name in file, fault distance, qubits, fits G6, stim calibration key
ROWS = [
    ("G4", "Google G4 (as run in Fig. 2)", T1 / "e4.json", "G4", 2, 12, "-", "G4-CX"),
    ("G6s", "Google G4 G6-style (as run in Fig. 4)", T2 / "e4_G4_G6style.json", "G4_G6style", 2, 12, "yes (Google's own)", "G4-G6style"),
    ("cs02", "**cs02 (ours, main result)**", T2 / "e4_cont_success02.json", "cont_success02", 3, 12, "no", "success02"),
] + [(f"#{n}", f"#{n} (ours, G6-fit)" + (" **chosen**" if n == 0 else ""), T3 / f"e4_g6fit{n:02d}.json",
      f"g6fit{n:02d}", 3, nq, "yes", None)
     for n, nq in [(0, 13), (1, 13), (2, 13), (3, 13), (4, 14), (5, 14), (6, 14), (7, 15), (9, 15)]]


def one_in(x):
    return f"1 in {1 / x:,.0f}" if x > 0 else "0 events"


def ratio_ci(k1, n1, k2, n2):
    """Rate ratio (k1/n1)/(k2/n2) and its 95 % interval."""
    r = (k1 / n1) / (k2 / n2)
    w = 1.96 * math.sqrt(1 / k1 + 1 / k2)
    return r, r * math.exp(-w), r * math.exp(w)


def main():
    cal = json.loads((ROOT / "results" / "continuing_validation.json").read_text())["designs"]
    data = {}
    for key, label, f, name, fd, nq, g6, ck in ROWS:
        r = json.loads(f.read_text())["results"][name]
        q = r["logical_error_given_code"]
        data[key] = dict(label=label, fd=fd, nq=nq, g6=g6, shots=r["shots"], kept=r["kept"], k=q["events"], n=q["of"],
                         rate=q["rate"], ci=q["ci95"], acc=r["acceptance"], acc_se=r.get("acceptance_se"),
                         cal=cal[ck]["willow"]["calibration"]["rate_T"] if ck else None)
    base = data["G6s"]
    now = dt.datetime.now(dt.timezone(dt.timedelta(hours=9))).strftime("%Y-%m-%d %I:%M %p KST")
    L = [f"# Master results: Google's double check vs ours (written {now})", "",
         "Single source of the numbers for the paper and the slides. All QVM rows: Google's QVM "
         "(cirq_google 1.7 + qsimcirq, processor `willow_pink`, its Willow noise model), **real T gates**, "
         "double check alone starting from an ideal encoded T state, identical post-selection and decoding for "
         "every circuit. Generated by `master_results.py` from the test 1-3 result files.", "",
         "## 1. Error per kept T state and acceptance (Google QVM, real T)", "",
         "| circuit | fault distance | qubits | fits G6 grafting | shots | discarded (detector fired) | errors / kept in code | T error per kept T state (95 % CI) "
         "| acceptance | attempts per kept T state | vs Google G6-style (95 % CI) |",
         "|---|---|---|---|---|---|---|---|---|---|---|"]
    for key, d in data.items():
        lo, hi = d["ci"]
        if key == "G6s":
            vs = "baseline"
        else:
            r, rlo, rhi = ratio_ci(base["k"], base["n"], d["k"], d["n"])
            vs = f"{r:.1f}× ({rlo:.1f}× to {rhi:.1f}×)" if key != "G4" else f"{1 / r:.2f}× worse"
        acc = f"{100 * d['acc']:.1f} %" + (f" ± {100 * d['acc_se']:.2f} %" if d["acc_se"] else "")
        L.append(f"| {d['label']} | {d['fd']} | {d['nq']} | {d['g6']} | {d['shots']:,} | {d['shots'] - d['kept']:,} | {d['k']} / {d['n']:,} "
                 f"| {one_in(d['rate'])} ({one_in(hi)} to {one_in(lo)}) | {acc} | {1 / d['acc']:.2f} | {vs} |")
    r, rlo, rhi = ratio_ci(data["G4"]["k"], data["G4"]["n"], data["cs02"]["k"], data["cs02"]["n"])
    L += ["", f"- cs02 vs Google G4 (Fig. 2): **{r:.1f}×** (95 % CI {rlo:.1f}× to {rhi:.1f}×).",
          "- 'vs Google G6-style' = Google's error / ours (higher is better for us). Ratio CI: log-normal "
          "approximation for a ratio of Poisson rates.",
          "- Acceptance ± = one standard error.", "",
          "## 2. Same circuits under the other two environments (stim)", "",
          "| circuit | Willow calibration model (stim) | SI1000, p = 0.23 % (cliffordea) |", "|---|---|---|"]
    si = {"G4": "1 in 164,000", "G6s": "1 in 209,000", "cs02": "1 in 766,000"}  # SUMMARY_improvements.md sec. 7
    for key in ("G4", "G6s", "cs02"):
        d = data[key]
        L.append(f"| {d['label']} | {one_in(d['cal'])} | {si[key]} |")
    c = data["cs02"]
    L += ["", f"- cs02 vs G6-style: {data['G6s']['cal'] / c['cal']:.1f}× (calibration), 3.7× (SI1000), "
          f"{ratio_ci(base['k'], base['n'], c['k'], c['n'])[0]:.1f}× (QVM): the three environments agree.",
          "- SI1000 values are from `SUMMARY_improvements.md` section 7 (`results/si1000.json`).", "",
          "## 3. Fault distance with real T (QVM fault injection, E3)", "",
          "Every single fault and every pair of faults injected with real T gates; the count is the number of "
          "kept shots with a wrong T state. All agree with cliffordea.", ""]
    rows3 = [("Google G4 G6-style", T2 / "e3_G4_G6style.json", "G4_G6style"),
             ("cs02", T2 / "e3_cont_success02.json", "cont_success02")] + \
            [(f"#{n}", T3 / f"e3_g6fit{n:02d}.json", f"g6fit{n:02d}") for n in (0, 1, 2, 3, 4, 5, 6, 7, 9)]
    L += ["| circuit | single faults | fault pairs | wrong T kept at 2 faults (real T / cliffordea) | fault distance |",
          "|---|---|---|---|---|"]
    for lab, f, name in rows3:
        s = json.loads(f.read_text())["designs"][name]["summary"]
        m = s["all2"]["real"].get("malignant", 0)
        L.append(f"| {lab} | {s['single']['n']:,} | {s['all2']['n']:,} | {m} / {s['all2']['cliffordea'].get('malignant', 0)} "
                 f"| {2 if m else 3} |")
    L += ["", "## Sources", "",
          "- Test 1: `test1_fd3_circuits_vs_google_fig2/results/e4.json` (G4).",
          "- Test 2: `test2_cs02_continuing_data_vs_google/results/` (G4 G6-style, cs02).",
          "- Test 3: `test3_full_qec_realT_lowT_sim_ours_vs_google_g6/results/qvm/` (the 9 G6-fit circuits).",
          "- stim calibration model: `results/continuing_validation.json`.", ""]
    (HERE / "MASTER_RESULTS.md").write_text("\n".join(L))
    print(HERE / "MASTER_RESULTS.md")


if __name__ == "__main__":
    main()
